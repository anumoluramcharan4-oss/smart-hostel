// Generate 120 rooms across 4 blocks (30 per block, 3 floors, 10 rooms per floor)
function generate120Rooms(): Room[] {
  const rooms: Room[] = []
  const blockDefs = [
    { id: 'blk-a', name: 'Block A (Newton)', prefix: 'A' },
    { id: 'blk-b', name: 'Block B (Aryabhata)', prefix: 'B' },
    { id: 'blk-c', name: 'Block C (Ramanujan)', prefix: 'C' },
    { id: 'blk-d', name: 'Block D (Kalam)', prefix: 'D' },
  ]

  blockDefs.forEach((blk) => {
    for (let floor = 1; floor <= 3; floor++) {
      for (let roomIdx = 1; roomIdx <= 10; roomIdx++) {
        const roomNum = `${blk.prefix}-${floor}${roomIdx < 10 ? '0' + roomIdx : roomIdx}`
        const isTriple = roomIdx % 3 === 0
        const isSingle = roomIdx % 7 === 0
        const capacity = isSingle ? 1 : isTriple ? 3 : 2
        const type = isSingle ? 'single' : isTriple ? 'triple' : 'double'

        // Determine occupants from STUDENTS list matching room
        const matchedStudents = STUDENTS.filter((s) => s.roomNumber === roomNum)
        let occupants = matchedStudents.map((s) => ({
          id: s.id,
          name: s.name,
          rollNo: s.rollNo,
          bed: s.bedNumber,
          course: s.course,
          avatar: s.avatar,
        }))

        // Under maintenance for 2 specific rooms
        const isMaintenance = roomNum === 'A-309' || roomNum === 'C-209'
        const occupied = isMaintenance ? 0 : Math.min(occupants.length, capacity)
        const status = isMaintenance
          ? 'maintenance'
          : occupied === capacity
          ? 'occupied'
          : 'available'

        rooms.push({
          id: `rm-${roomNum.toLowerCase()}`,
          number: roomNum,
          blockId: blk.id,
          blockName: blk.name,
          floor,
          type,
          capacity,
          occupied,
          status,
          occupants,
          amenities: ['High-speed Wi-Fi', 'Study Lamp', 'Attached Balcony', 'Geyser'],
        })
      }
    }
  })

  return rooms
}

